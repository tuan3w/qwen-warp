"""Tables for pld-tail-engine from the A/B json files written by engine/tests/bench_pld.py (results/ab_*.json).

  python3 experiments/2026-11-01-pld-tail-engine/analyze_ab.py [--out results/tables.md]
Per task and mode: median over reps of tokens / time (tokens after the first, decode wall time, prefill excluded).  Per class: pooled tokens / pooled time of the per-task medians; ratio =
mode / base on the same tasks; 95% CI = percentile bootstrap over TASKS (10,000 resamples).  E = emitted tokens / cycles pooled.
"""
import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / "results"


def load(fn):
    p = RES / fn
    return json.loads(p.read_text()) if p.exists() else None


def per_task(d, mode):
    """-> {task: (cls, tokens, sec, emitted, cycles)} medians over reps"""
    by = defaultdict(list)
    for r in d["rows"]:
        if r["mode"] == mode:
            by[r["task"]].append(r)
    out = {}
    for t, rs in by.items():
        out[t] = (rs[0]["cls"], statistics.median(r["tokens"] for r in rs), statistics.median(r["sec"] for r in rs), statistics.median(r["emitted"] for r in rs), statistics.median(r["cycles"] for r in rs))
    return out


def ratio_ci(a, b, ids, nb=10000, seed=0):
    n = np.array([a[i][1] for i in ids], float)
    t = np.array([a[i][2] for i in ids], float)
    nb_ = np.array([b[i][1] for i in ids], float)
    tb = np.array([b[i][2] for i in ids], float)
    pt = (n.sum() / t.sum()) / (nb_.sum() / tb.sum())
    if len(ids) < 2:
        return pt, pt, pt
    ix = np.random.default_rng(seed).integers(0, len(ids), (nb, len(ids)))
    rs = (n[ix].sum(1) / t[ix].sum(1)) / (nb_[ix].sum(1) / tb[ix].sum(1))
    lo, hi = np.percentile(rs, [2.5, 97.5])
    return pt, lo, hi


def table(fn, modes, title):
    d = load(fn)
    if d is None:
        return f"\n(no {fn})\n"
    base = per_task(d, "base")
    cls = defaultdict(list)
    for t, v in base.items():
        cls[v[0]].append(t)
    L = [f"\n### {title}\n(`{fn}`, {d['args']['reps']} reps, T={d['args']['temperature']}, tasks per class: " + ", ".join(f"{c} {len(v)}" for c, v in sorted(cls.items())) + ")\n"]
    L.append("| class | base tok/s (E) | " + " | ".join(f"{m} tok/s (E) x ratio [95% CI]" for m in modes if m != "base") + " |")
    L.append("|---|---|" + "---|" * (len(modes) - 1))
    pm = {m: per_task(d, m) for m in modes}
    groups = [(c, cls[c]) for c in sorted(cls)]
    if all(c in cls for c in "abc"):
        groups.append(("a-c", [i for c in "abc" for i in cls[c]]))
    for c, ids in groups:
        def rate(m, ids=ids):
            return sum(pm[m][i][1] for i in ids) / sum(pm[m][i][2] for i in ids)

        def E(m, ids=ids):
            return sum(pm[m][i][3] for i in ids) / sum(pm[m][i][4] for i in ids)

        cells = []
        for m in modes:
            if m == "base":
                continue
            r, lo, hi = ratio_ci(pm[m], pm["base"], ids)
            cells.append(f"{rate(m):.1f} ({E(m):.2f}) x{r:.3f} [{lo:.3f}, {hi:.3f}]")
        L.append(f"| {c} | {rate('base'):.1f} ({E('base'):.2f}) | " + " | ".join(cells) + " |")
    L.append("")
    L.append("per task (tok/s, ratio to base):")
    L.append("| task | n | base | " + " | ".join(m for m in modes if m != "base") + " |")
    L.append("|---|---|---|" + "---|" * (len(modes) - 1))
    for t in sorted(base):
        cells = []
        for m in modes:
            if m == "base":
                continue
            cells.append(f"{pm[m][t][1] / pm[m][t][2]:.1f} (x{(pm[m][t][1] / pm[m][t][2]) / (base[t][1] / base[t][2]):.3f})")
        L.append(f"| {t} | {int(base[t][1])} | {base[t][1] / base[t][2]:.1f} | " + " | ".join(cells) + " |")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(RES / "tables.md"))
    a = ap.parse_args()
    out = ["# pld-tail-engine: A/B tables (generated by analyze_ab.py)\n"]
    out.append(table("ab_e6_greedy.json", ["base", "pld", "adapt"], "E6 workload (32 tasks), greedy, MTP k=3 chain + prompt-lookup tail (m=3, Lt=4) vs committed cycles; `adapt` = the removed online-EMA width back-off (dead end)"))
    out.append(table("ab_e6_t1.json", ["base", "pld"], "E6 workload (32 tasks), T=1.0 top_k 20 top_p .95 sampling (exact speculative sampling, tail = delta proposals)"))
    out.append(table("ab_e6_de_m.json", ["base", "pld3", "pld4", "pld6"], "E6 classes d / e, tail gate m = 3 / 4 / 6"))
    out.append(table("ab_long_greedy.json", ["base", "pld3", "pld4", "pld6"], "class f: long-context (6K tokens) prose / summarisation prompts, tail gate m = 3 / 4 / 6"))
    out.append(table("ab_e0_greedy_m.json", ["base", "pld3", "pld4", "pld6"], "E0 prompts (code / prose / math / 8K), greedy, tail gate m = 3 / 4 / 6"))
    out.append(table("ab_e0_greedy.json", ["base", "notail", "pld"], "E0 prompts, greedy: `notail` = host-driven loop with the tail gate closed (per-cycle round trip), `pld` = tail m=3"))
    out.append(table("ab_e0_t1.json", ["base", "pld"], "E0 prompts, T=1.0 sampling (single sampled trajectories differ between modes: +-2% noise per prompt)"))
    txt = "\n".join(out)
    Path(a.out).write_text(txt)
    print(txt)


if __name__ == "__main__":
    main()
